import numpy as np

x = np.array([-0.135, 0.715, 1.565, 2.415, 3.265])
y = np.array([-2.132, -2.113, -1.613, -0.842, 1.204])
h = x[1] - x[0]

# 1.3. а) У точці x = 1.565 (симетричні 5-точкові формули)
f_prime_a = (1 / (12 * h)) * (y[0] - 8*y[1] + 8*y[3] - y[4])
f_pprime_a = (1 / (24 * h**2)) * (-2*y[0] + 32*y[1] - 60*y[2] + 32*y[3] - 2*y[4])
print(f"1.3. а) x = 1.565: f' = {f_prime_a:.4f}, f'' = {f_pprime_a:.4f}")

# 1.3. б) У точці x = 2.415 (несиметричні формули назад для 5 точок)
f_prime_b = (1 / (12 * h)) * (-y[0] + 6*y[1] - 18*y[2] + 10*y[3] + 3*y[4])
f_pprime_b = (1 / (24 * h**2)) * (-2*y[0] + 8*y[1] + 12*y[2] - 40*y[3] + 22*y[4])
print(f"1.3. б) x = 2.415: f' = {f_prime_b:.4f}, f'' = {f_pprime_b:.4f}")

# 1.4. Порівняння результатів у точці x = 1.565
print("\n1.4. Порівняння результатів у точці x = 1.565:")
print("- Значення, отримані за методом Стірлінга та найпростішими симетричними формулами, збігаються.")
print("- Центральні формули є більш точними для внутрішніх вузлів завдяки використанню симетричних шаблонів.")
